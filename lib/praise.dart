/// Геймификация: локальный генератор похвалы и идей наград.
/// Работает офлайн, без LLM. Тексты персонализируются: имя пользователя
/// и род обращения берутся из UserProfile (загружается при старте).
library;

import 'dart:math';

import 'profile.dart';

class Praise {
  static final _rnd = Random();

  static const List<String> _forTask = [
    'отлично! Ещё один шаг сделан — ты двигаешься именно туда, куда решил(а).',
    'задача закрыта. Так держать: дисциплина — это твоя суперсила.',
    'готово! Каждое такое действие приближает большую цель.',
    'молодец! Даже маленький шаг — это движение вперёд, а ты его сделал(а).',
    'выполнено! Горжусь твоим упорством.',
  ];

  static const List<String> _forKeyTask = [
    'это было КЛЮЧЕВОЕ действие — без него цель была бы недостижима. Ты справился(ась)!',
    'ключевая задача закрыта! Именно такие шаги отделяют мечту от результата.',
  ];

  static const List<String> _forGoal = [
    'ЦЕЛЬ ДОСТИГНУТА! Огромная работа позади — ты это сделал(а). Горжусь тобой!',
    'победа! Цель закрыта. Вспомни, какое ощущение ты хотел(а) получить — оно твоё.',
    'цель достигнута! Это доказывает: твои планы работают, потому что работаешь ты.',
  ];

  static const List<String> _forHabit = [
    'привычка отмечена! Регулярность сильнее мотивации — и она у тебя есть.',
    'ещё один день в серии. Ты становишься тем, кем решил(а) стать.',
    'сделано! Ежедневные действия — это кирпичи большого результата.',
  ];

  /// Идеи наград («приз») после закрытия задачи/цели.
  /// Этот же список — варианты в выпадающем окне выбора награды
  /// за продуктивный день (экран «Сегодня»).
  static const List<String> rewardIdeas = [
    'Вкусняшка — желательно полезная: фрукты, орехи, что любишь.',
    'Отдых: пара часов или целый день только для себя.',
    'Купить себе вещь, о которой давно думаешь.',
    'Творческий процесс или любимое занятие на день и больше.',
    'Прогулка, спорт, бассейн — телу тоже нужна награда.',
    'Сериал или фильм — вечер без чувства вины.',
    'Встреча с друзьями или звонок близким.',
    'Сладкое к чаю — маленькое торжество.',
  ];

  // ---------- Похвала за продуктивный день (экран «Сегодня») ----------
  /// Лёгкое уведомление: выполнено 60–84% задач дня.
  static const List<String> _dayLight = [
    'отлично провёл день! А теперь позволь себе чуть больше, чем можно 😉',
    'больше половины задач дня закрыто — день явно удался 😉',
    'хороший темп! Большая часть плана сделана, осталось совсем чуть-чуть 😉',
    'день идёт отлично: выполнено больше 60% задач. Так держать 😉',
    'продуктивный день набирает обороты — ты большой молодец 😉',
  ];

  /// Эмоциональное подбадривание: выполнено 80–99% задач дня.
  static const List<String> _dayStrong = [
    'вот это мощь! Почти всё сделано — ты сегодня просто машина результатов 💪',
    'невероятно! День почти закрыт полностью. Я тобой горжусь, честное слово ✨',
    'ты сегодня на высоте! Ещё чуть-чуть — и день будет идеальным 🔥',
    'потрясающая результативность! Такие дни делают большие цели реальностью 🚀',
  ];

  /// Финал: выполнены ВСЕ задачи дня. Обращение — по роду из профиля
  /// (там же, где выбиралось «как к мужчине / как к женщине»).
  static String forDayFull() {
    switch (UserProfile.gender) {
      case 'f':
        return '${UserProfile.name.isEmpty ? '' : '${UserProfile.name}, '}'
            'ты нереальная красотка! Все задачи дня закрыты. Обожаю тебя! 😘';
      case 'm':
        return '${UserProfile.name.isEmpty ? '' : '${UserProfile.name}, '}'
            'ты нереально крут! Все задачи дня закрыты. Обожаю тебя! 😎';
      default:
        return 'все задачи дня закрыты — ты просто космос! Обожаю тебя! 🤩';
    }
  }

  /// Сообщение о награде за день по порогу:
  /// tier 1 (60%+), tier 2 (80%+), tier 3 (100%, особое).
  static String forDay(int tier) {
    if (tier >= 3) return forDayFull();
    if (tier == 2) {
      return personalize(_dayStrong[_rnd.nextInt(_dayStrong.length)]);
    }
    return personalize(_dayLight[_rnd.nextInt(_dayLight.length)]);
  }


  /// Персонализация текста под пользователя: имя + грамматический род.
  /// Маркеры «(а)» / «(ась)» раскрываются по UserProfile.gender.
  static String personalize(String s) {
    var out = s;
    if (UserProfile.gender == 'f') {
      out = out
          .replaceAll('справился(ась)', 'справилась')
          .replaceAll('сделал(а)', 'сделала')
          .replaceAll('решил(а)', 'решила')
          .replaceAll('хотел(а)', 'хотела');
    } else if (UserProfile.gender == 'm') {
      out = out
          .replaceAll('справился(ась)', 'справился')
          .replaceAll('сделал(а)', 'сделал')
          .replaceAll('решил(а)', 'решил')
          .replaceAll('хотел(а)', 'хотел');
    }
    // Род неизвестен — оставляем нейтральные формы «сделал(а)» как есть.
    if (UserProfile.name.isNotEmpty) {
      out = '${UserProfile.name}, $out';
    }
    return out;
  }

  static String forTask({bool key = false}) {
    if (key) return personalize(_forKeyTask[_rnd.nextInt(_forKeyTask.length)]);
    return personalize(_forTask[_rnd.nextInt(_forTask.length)]);
  }

  static String forGoal() => personalize(_forGoal[_rnd.nextInt(_forGoal.length)]);

  static String forHabit() => personalize(_forHabit[_rnd.nextInt(_forHabit.length)]);

  static String rewardIdea() => rewardIdeas[_rnd.nextInt(rewardIdeas.length)];
}
